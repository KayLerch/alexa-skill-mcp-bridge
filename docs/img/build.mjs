const vars = (palette) =>
  Object.entries(palette)
    .filter(([k]) => k !== 'style')
    .map(([k, v]) => `--${k}: ${v}`)
    .join('; ');
const AUTO = {
  ...Object.fromEntries(Object.keys(LIGHT).map((k) => [k, `var(--${k})`])),
  style:
    '  <style>\n' +
    `    :root { ${vars(LIGHT)} }\n` +
    `    @media (prefers-color-scheme: dark) { :root { ${vars(DARK)} } }\n` +
    '  </style>',
};

// Also escapes the double quote: esc() feeds the aria-label attribute as well as text nodes.
const esc = (s) =>
  String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
const text = (x, y, s, o = {}) =>
  `  <text x="${x}" y="${y}"${o.anchor ? ` text-anchor="${o.anchor}"` : ''} font-size="${o.size ?? 13}"` +
  `${o.weight ? ` font-weight="${o.weight}"` : ''}${o.spacing ? ` letter-spacing="${o.spacing}"` : ''}` +
  ` fill="${o.fill}">${esc(s)}</text>`;
const box = (x, y, w, h, p, o = {}) =>
  `  <rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${o.r ?? 14}" fill="${o.fill ?? p.card}" stroke="${o.stroke ?? p.stroke}"${o.dash ? ` stroke-dasharray="${o.dash}"` : ''}${o.sw ? ` stroke-width="${o.sw}"` : ''}/>`;

function open(w, h, p, aria, style) {
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" role="img" aria-label="${esc(aria)}">`,
    `  <!-- Generated by docs/img/build.mjs. Do not edit by hand. -->`,
    ...(style ? [style] : []),
    `  <rect width="${w}" height="${h}" fill="${p.bg}"/>`,
    `  <defs>`,
    `    <marker id="f" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="6" markerHeight="6" orient="auto"><path d="M0 0 L10 5 L0 10 z" fill="${p.arrow}"/></marker>`,
    `    <marker id="b" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="6" markerHeight="6" orient="auto"><path d="M0 0 L10 5 L0 10 z" fill="${p.back}"/></marker>`,
    `  </defs>`,
    `  <g font-family="${FONT}">`,
  ];
}
const close = () => ['  </g>', '</svg>', ''];

// ---------------------------------------------------------------- wide version

const ARIA_WIDE =
  'The bridge at a glance, left to right: an Alexa+ device, the Alexa Skill, a thin Alexa Skill Lambda and AgentCore ' +
  'Runtime inside AWS us-east-1, and your MCP server outside it. The runtime holds a Strands agent on Nova 2 Lite, an ' +
  'MCP client over Streamable HTTP, AgentCore Memory and a widget renderer on headless Chromium. Numbered arrows 1 ' +
  'to 4 carry the request rightwards to your server, and arrows 5 to 8 carry the answer back leftwards to the ' +
  'device, as speech and, where the server offers a widget, as an image shown on the screen. A numbered legend ' +
  'below the diagram explains all eight steps, and two callouts under it cover a slow ' +
  'turn, where the Alexa Skill says "One moment." while the agent keeps working, and a screen, where the agent ' +
  "renders your server's widget to an image the Alexa Skill shows full screen.";

function wide(p) {
  const W = 1120,
    H = 472;
  const s = open(W, H, p, ARIA_WIDE, p.style);
  const FWD = 120,
    BACK = 166;

  s.push(
    box(410, 28, 483, 238, p, { r: 16, fill: 'none', stroke: p.boundary, sw: 1.4, dash: '7 5' }),
  );
  s.push(
    text(426, 50, 'AWS · us-east-1', {
      size: 10.5,
      weight: '600',
      spacing: 1.1,
      fill: p.boundarytext,
    }),
  );

  const node = (x, w, eyebrow, accent, title, sub, y = 86, h = 112) => {
    s.push(box(x, y, w, h, p));
    s.push(
      text(x + w / 2, y + 30, eyebrow, {
        anchor: 'middle',
        size: 9,
        weight: '600',
        spacing: 1.1,
        fill: p[accent],
      }),
    );
    s.push(
      text(x + w / 2, y + 56, title, { anchor: 'middle', size: 14, weight: '600', fill: p.title }),
    );
    if (sub) s.push(text(x + w / 2, y + 76, sub, { anchor: 'middle', size: 10.5, fill: p.sub }));
  };

  /** One numbered hop across a gap: the request runs right, the answer runs back left. */
  const hop = (x0, x1, n, forward) => {
    const y = forward ? FWD : BACK;
    const colour = forward ? p.arrow : p.back;
    const [from, to] = forward ? [x0 + 3, x1 - 7] : [x1 - 3, x0 + 7];
    s.push(
      `  <line x1="${from}" y1="${y}" x2="${to}" y2="${y}" stroke="${colour}" stroke-width="1.6"${forward ? '' : ' stroke-dasharray="4 3"'} marker-end="url(#${forward ? 'f' : 'b'})"/>`,
    );
    const cx = (x0 + x1) / 2;
    s.push(
      `  <circle cx="${cx}" cy="${y}" r="11" fill="${forward ? p.alexa : p.back}" stroke="${p.bg}" stroke-width="2"/>`,
    );
    s.push(text(cx, y + 4, n, { anchor: 'middle', size: 11, weight: '700', fill: p.onaccent }));
  };

  node(24, 138, 'ALEXA+ DEVICE', 'alexa', 'The user speaks', 'or types in the simulator');
  node(227, 138, 'ALEXA+', 'alexa', 'Alexa Skill', 'intent + slots');
  node(430, 158, 'AWS LAMBDA', 'aws', 'Alexa Skill Lambda', 'thin: speech and screen');

  s.push(box(653, 40, 220, 214, p));
  s.push(
    text(763, 68, 'AMAZON BEDROCK', {
      anchor: 'middle',
      size: 9,
      weight: '600',
      spacing: 1.1,
      fill: p.aws,
    }),
  );
  s.push(
    text(763, 90, 'AgentCore Runtime', {
      anchor: 'middle',
      size: 14,
      weight: '600',
      fill: p.title,
    }),
  );
  s.push(text(763, 108, 'one microVM per user', { anchor: 'middle', size: 10.5, fill: p.sub }));
  [
    ['Strands agent · Nova 2 Lite'],
    ['MCP client · Streamable HTTP'],
    ['AgentCore Memory'],
    ['Widget renderer · Chromium'],
  ].forEach(([label], i) => {
    const y = 118 + i * 32;
    s.push(box(667, y, 192, 28, p, { r: 8, fill: p.chip, stroke: p.chipstroke }));
    s.push(text(763, y + 18.5, label, { anchor: 'middle', size: 10, fill: p.title }));
  });

  node(938, 158, 'OUTSIDE AWS', 'mcp', 'Your MCP server', 'no changes needed');

  // Four gaps, each carrying the request one way and the answer the other.
  [
    [162, 227],
    [365, 430],
    [588, 653],
    [873, 938],
  ].forEach(([x0, x1], i) => {
    hop(x0, x1, i + 1, true);
    hop(x0, x1, 8 - i, false);
  });

  s.push(`  <line x1="24" y1="290" x2="${W - 24}" y2="290" stroke="${p.rule}" stroke-width="1"/>`);
  const legend = [
    [1, true, 'The user speaks to an Alexa+ device, or types in the test simulator.'],
    [
      2,
      true,
      "Alexa+ matches utterances against the Alexa Skill's interaction model, generated from your tools.",
    ],
    [3, true, 'The Alexa Skill Lambda forwards the request. It holds no MCP and no model logic.'],
    [
      4,
      true,
      'The agent picks a tool, fills its arguments, and calls your server over Streamable HTTP.',
    ],
    [
      5,
      false,
      'Your server returns a result, with a widget if it offers one, or asks a question back.',
    ],
    [
      6,
      false,
      'The agent writes one short spoken answer or the next question, and renders that widget.',
    ],
    [7, false, 'The Lambda sends the speech as SSML and the image as one APL screen.'],
    [8, false, 'The device speaks and shows it. A parked question resumes the same call.'],
  ];
  legend.forEach(([n, forward, line], i) => {
    const x = i < 4 ? 24 : 572;
    const y = 320 + (i % 4) * 24;
    s.push(`  <circle cx="${x + 9}" cy="${y - 4}" r="9" fill="${forward ? p.alexa : p.back}"/>`);
    s.push(
      text(x + 9, y, String(n), { anchor: 'middle', size: 10.5, weight: '700', fill: p.onaccent }),
    );
    s.push(text(x + 24, y, line, { size: 11, fill: p.sub }));
  });

  // Neither is a step in the round trip, so they get their own band rather than a number.
  s.push(`  <line x1="24" y1="406" x2="${W - 24}" y2="406" stroke="${p.rule}" stroke-width="1"/>`);
  [
    [
      'aws',
      'Slow turn',
      'the Alexa Skill says "One moment." while the agent keeps working, then speaks the result.',
    ],
    [
      'mcp',
      'Screen',
      "the agent renders your server's widget to an image, and the Alexa Skill shows it full screen.",
    ],
  ].forEach(([accent, label, line], i) => {
    const y = 434 + i * 24;
    s.push(`  <rect x="24" y="${y - 12}" width="11" height="11" rx="3" fill="${p[accent]}"/>`);
    s.push(text(43, y, label, { size: 11, weight: '600', fill: p.title }));
    s.push(text(126, y, line, { size: 11, fill: p.sub }));
  });
  return [...s, ...close()].join('\n');
}

for (const [name, svg] of [
  ['bridge.light.svg', wide(LIGHT)],
  ['bridge.dark.svg', wide(DARK)],
  ['bridge.auto.svg', wide(AUTO)],
]) {
  writeFileSync(join(OUT, name), svg, 'utf8');
  console.log(`${name}  ${svg.length} bytes`);
}
