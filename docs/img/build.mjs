  card: '#ffffff',
  stroke: '#d5dbe1',
  title: '#1f2328',
  sub: '#5b6570',
  chip: '#f6f8fa',
  chipstroke: '#dfe3e8',
  arrow: '#9aa4ae',
  label: '#5b6570',
  rule: '#e6eaee',
  alexa: '#0a84c4',
